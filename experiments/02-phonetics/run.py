"""Experiment 02: how accurately does each engine pronounce Castilian Spanish?

Every text in texts/phonetics.jsonl is generated by each engine and variant of config.yaml with every seed, then
scored by Whisper (WER) and by the phonetic judge. Takes where Whisper reports no error but the phonetic judge flags
words show what WER alone would miss.

Usage: uv run python experiments/02-phonetics/run.py [--engines name,...] [--rescore]
"""
from pathlib import Path
from statistics import mean, median

import soundfile as sf

from labtts.engines import load_engine
from labtts.judges.phonetic import PhoneticJudge
from labtts.judges.whisper import WhisperJudge, word_error_rate
from labtts.paths import experiment_output_dir
from labtts.records import (engines_to_run, format_flagged_words, load_engine_results, markdown_table,
                            parse_arguments, save_engine_results, update_readme_results, voice_used)
from labtts.texts import load_config, load_items
from labtts.voices import load_voice

EXPERIMENT_DIR = Path(__file__).resolve().parent


def generate_takes(engine_name: str, variants: dict, config: dict, texts: list[dict], audio_dir: Path) -> tuple[list[dict], str]:
    engine = load_engine(engine_name, load_voice(config["voice"]))
    takes = []
    for variant_name, overrides in variants.items():
        for item in texts:
            for seed in config["seeds"]:
                synthesis = engine.synthesize(item["text"], seed, overrides)
                path = audio_dir / f"{variant_name}_{item['id']}_seed{seed}.wav"
                sf.write(path, synthesis.wave, synthesis.sample_rate)
                takes.append({"variant": variant_name, "text_id": item["id"], "seed": seed, "wav": path.name,
                              "duration_s": round(synthesis.duration_seconds, 2),
                              "real_time_factor": round(synthesis.real_time_factor, 3),
                              "hit_token_limit": synthesis.hit_token_limit})
                print(f"generated {engine_name}/{path.name}: {synthesis.duration_seconds:.1f} s", flush=True)
    voice_label = engine.voice_label
    engine.close()
    return takes, voice_label


def score_takes(takes: list[dict], texts_by_id: dict, audio_dir: Path, phonetic_judge, whisper_judge) -> None:
    for take in takes:
        wave, sample_rate = sf.read(audio_dir / take["wav"], dtype="float32")
        reference = texts_by_id[take["text_id"]]
        verdict = phonetic_judge.evaluate(reference, wave, sample_rate)
        transcript = whisper_judge.transcribe(wave, sample_rate)
        take.update({"phonetic_error_rate": round(verdict.error_rate, 4), "flagged_words": verdict.flagged_words,
                     "ctc_transcript": verdict.transcript, "whisper_transcript": transcript,
                     "word_error_rate": round(word_error_rate(reference, transcript), 4)})


def summarize(takes: list[dict]) -> dict:
    summary = {}
    for variant_name in dict.fromkeys(take["variant"] for take in takes):
        group = [take for take in takes if take["variant"] == variant_name]
        summary[variant_name] = {
            "takes": len(group),
            "phonetic_error_rate_mean": round(mean(take["phonetic_error_rate"] for take in group), 4),
            "takes_with_flagged_words": sum(bool(take["flagged_words"]) for take in group),
            "flagged_words": sum(len(take["flagged_words"]) for take in group),
            "word_error_rate_mean": round(mean(take["word_error_rate"] for take in group), 4),
            "takes_whisper_missed": sum(take["word_error_rate"] == 0 and bool(take["flagged_words"]) for take in group),
            "real_time_factor_median": round(median(take["real_time_factor"] for take in group), 3),
            "hit_token_limit": sum(take["hit_token_limit"] for take in group),
        }
    return summary


def render_readme(all_engines: dict, texts: list[dict]) -> str:
    sections = ["### By engine and variant", markdown_table(
        ["engine", "variant", "voice", "takes", "phonetic error (mean)", "takes with flagged words", "flagged words",
         "Whisper WER (mean)", "flagged but WER = 0", "real-time factor (median)"],
        [[engine_name, variant_name, voice_used(entry, variant_name), values["takes"], values["phonetic_error_rate_mean"],
          values["takes_with_flagged_words"], values["flagged_words"], values["word_error_rate_mean"],
          values["takes_whisper_missed"], values["real_time_factor_median"]]
         for engine_name, entry in all_engines.items() for variant_name, values in entry["results"]["summary"].items()])]
    by_text_rows = []
    for item in texts:
        for engine_name, entry in all_engines.items():
            takes = [take for take in entry["results"]["takes"] if take["text_id"] == item["id"]]
            by_text_rows.append([item["id"], item["focus"], engine_name,
                                 round(mean(take["phonetic_error_rate"] for take in takes), 4),
                                 ", ".join(f"{word['expected']}→{word['heard']}" for take in takes
                                           for word in take["flagged_words"]) or "—"])
    sections += ["### By text", markdown_table(["text", "focus", "engine", "phonetic error (mean)", "flagged words"],
                                               by_text_rows)]
    missed = [(engine_name, take) for engine_name, entry in all_engines.items() for take in entry["results"]["takes"]
              if take["word_error_rate"] == 0 and take["flagged_words"]]
    if missed:
        sections += ["### Flagged by the phonetic judge, perfect for Whisper", markdown_table(
            ["engine", "take", "flagged words", "Whisper heard"],
            [[engine_name, take["wav"], ", ".join(f"{word['expected']}→{word['heard']}" for word in take["flagged_words"]),
              take["whisper_transcript"]] for engine_name, take in missed])]
    return "\n\n".join(sections)


def main() -> None:
    arguments = parse_arguments()
    config = load_config(EXPERIMENT_DIR)
    texts = load_items(config["texts"])
    previous = load_engine_results(EXPERIMENT_DIR)
    runs = {}
    for engine_name, variants in engines_to_run(config, arguments).items():
        audio_dir = experiment_output_dir(f"{EXPERIMENT_DIR.name}/{engine_name}")
        runs[engine_name] = ((previous[engine_name]["results"]["takes"], previous[engine_name]["voice"]) if arguments.rescore
                             else generate_takes(engine_name, variants, config, texts, audio_dir)) + (audio_dir,)
    if arguments.generate_only:  # judged later, with --rescore in the lab's environment
        for engine_name, (takes, voice_label, _) in runs.items():
            save_engine_results(EXPERIMENT_DIR, config, engine_name, voice_label, {"takes": takes})
        return
    # the judges load once, after every engine has released the GPU
    phonetic_judge, whisper_judge = PhoneticJudge(), WhisperJudge()
    all_engines = previous
    for engine_name, (takes, voice_label, audio_dir) in runs.items():
        score_takes(takes, {item["id"]: item["text"] for item in texts}, audio_dir, phonetic_judge, whisper_judge)
        all_engines = save_engine_results(EXPERIMENT_DIR, config, engine_name, voice_label,
                                          {"summary": summarize(takes), "takes": takes})
    update_readme_results(EXPERIMENT_DIR, render_readme(all_engines, texts))


if __name__ == "__main__":
    main()
